// دالة اختيار النظام الغذائي يدوياً
// دالة لتوليد وقت التحضير ومستوى الصعوبة برمجياً (حتى لا تضطري لتعديل 90 وصفة)
function getMealMeta(type) {
    if (type === 'breakfast') return { time: '⏱️ 10 Mins', diff: '🟢 Easy' };
    if (type === 'snacks') return { time: '⏱️ 5 Mins', diff: '🟢 Easy' };
    if (type === 'lunch') return { time: '⏱️ 25 Mins', diff: '🟡 Medium' };
    return { time: '⏱️ 15 Mins', diff: '🟢 Easy' };
}

function setDiet(dietType, element) {
    currentDiet = dietType;
    document.querySelectorAll('.diet-btn').forEach(btn => btn.classList.remove('active'));
    element.classList.add('active');
    filterMeals(currentCategory);
}

function filterMeals(category, event = null) {
    currentCategory = category;

    document.querySelectorAll('.tab-item').forEach(btn => btn.classList.remove('active'));
    if (event) {
        event.target.classList.add('active');
    } else {
        const activeTab = Array.from(document.querySelectorAll('.tab-item'))
            .find(btn => btn.innerText.toLowerCase().includes(category.toLowerCase()));
        if (activeTab) activeTab.classList.add('active');
    }

    const grid = document.getElementById('mealsGrid');
    grid.innerHTML = '';

    const filtered = mealsData.filter(meal => {
        const matchesCategory = meal.type === category;
        const matchesDiet = meal.diets.includes(currentDiet);
        const matchesHealth = isHealthFilterActive ? meal.healthSafe === true : true;
        return matchesCategory && matchesDiet && matchesHealth;
    });

    if (filtered.length === 0) {
        grid.innerHTML = `
        <div class="col-span-full text-center py-20">
            <p class="text-gray-400 text-lg">No meals found matching your criteria in ${category}.</p>
        </div>`;
        return;
    }

    filtered.forEach((meal, index) => {
        const meta = getMealMeta(meal.type); // سحب الوقت والصعوبة
        const card = document.createElement('div');
        card.className = 'meal-card';
        card.style.animationDelay = `${index * 0.1}s`;
        card.onclick = () => openRecipe(meal.id);

        card.innerHTML = `
        <img src="${meal.image}" class="meal-image">
        <div class="meal-info">
            <div class="flex justify-between items-start mb-2">
                <h3 class="font-bold text-gray-800">${meal.title}</h3>
                <span class="text-[10px] bg-pink-100 text-pink-600 px-2 py-1 rounded-full">${currentDiet}</span>
            </div>
            <div class="flex gap-2 mb-3">
                <span class="text-[10px] bg-gray-50 text-gray-500 px-2 py-1 rounded border border-gray-100">${meta.time}</span>
                <span class="text-[10px] bg-gray-50 text-gray-500 px-2 py-1 rounded border border-gray-100">${meta.diff}</span>
            </div>
            <div class="macro-tags">
                <span class="tag text-pink-600">${meal.calories} kcal</span>
                <span class="tag text-blue-600">P: ${meal.protein}</span>
                <span class="tag text-green-600">C: ${meal.carbs}</span>
            </div>
        </div>
        `;
        grid.appendChild(card);
    });
}

